#!/usr/bin/env python3
"""Compiles the texts of the screen in the twenty-nine extra languages (the files of the folder `locales`) into core/locales_gen.hpp, and checks them.

    python -I tools/make_locales.py            writes core/locales_gen.hpp
    python -I tools/make_locales.py --check    fails when the file is out of date, a file has a key that does not exist, a text is empty or lacks what must stay
                                               (the name hmi.cfg), or a character of a text is not in the font of core/font_ranges.hpp

A file of the folder is `Key<TAB>text`, one per line; a line that starts with `#` is a comment; a key that is missing is shown in English (in Portuguese of Portugal
for pt-br and in French of France for fr-ca). `names.tsv` gives the name of every language in itself, in the order of the selector of the screen.
Copyright (C) 2026 JuanenRac (Electro Hobby 3D). GPL-3.0-or-later.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ROOT / "locales"
GEN = ROOT / "core" / "locales_gen.hpp"
RANGES = ROOT / "core" / "font_ranges.hpp"

BASE = ["en", "es", "it", "de", "fr", "pt", "zh", "ja"]
# Files that hold text the screen draws (the literals of these files must be in the font as well).
LITERAL_FILES = ["core/ui_text.hpp", "core/quality.hpp", "core/keyboard.hpp", "main/ui.cpp"]
# Texts that must keep a word whatever the language says.
MUST_KEEP = {"q.NeedServer": ["hmi.cfg"], "q.Checking": ["..."]}


def key_names() -> list[str]:
    text = (ROOT / "core" / "locales.hpp").read_text(encoding="utf-8")
    block = text[text.index("kKeyNames["):text.index("};", text.index("kKeyNames["))]
    return re.findall(r'"([a-z]+\.[A-Za-z_]+)"', block)


def read_tsv(path: Path) -> dict[str, str]:
    rows: dict[str, str] = {}
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            raise ValueError(f"{path.name}:{n}: no tab")
        key, value = line.split("\t", 1)
        if key in rows:
            raise ValueError(f"{path.name}:{n}: key {key} twice")
        rows[key] = value
    return rows


def languages() -> list[tuple[str, str]]:
    return [tuple(line.split("\t", 1)) for line in (LOCALES / "names.tsv").read_text(encoding="utf-8").splitlines() if line and not line.startswith("#")]  # type: ignore[misc]


def extra_codes() -> list[str]:
    return [c for c, _ in languages() if c not in BASE]


def literal_chars() -> set[str]:
    """The characters of the string literals of the files that draw text."""
    chars: set[str] = set()
    for rel in LITERAL_FILES:
        text = (ROOT / rel).read_text(encoding="utf-8")
        for lit in re.findall(r'"((?:[^"\\\n]|\\.)*)"', text):
            chars.update(re.sub(r"\\.", "", lit))
    return chars


def used_chars() -> set[str]:
    """Every character the screen can draw: printable ASCII, the literals of the code, the texts of the extra languages and the names of the languages."""
    chars = {chr(c) for c in range(0x20, 0x7F)}
    chars |= {c for c in literal_chars() if ord(c) >= 0x20}
    for code in extra_codes():
        for value in read_tsv(LOCALES / f"{code}.tsv").values():
            chars.update(value)
    for _, name in languages():
        chars.update(name)
    return chars


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate() -> str:
    keys = key_names()
    langs = languages()
    out = ["// EH3D-NODE-BUNGARD-HMI - core/locales_gen.hpp",
           "// Copyright (C) 2026 JuanenRac (Electro Hobby 3D). GPL-3.0-or-later.",
           "// Generated by tools/make_locales.py from the files of the folder `locales`: do not edit by hand. A null is a text the language lacks.",
           "#pragma once", "", "#include <cstddef>", "", "namespace hmi {", "namespace gen {", ""]
    codes = extra_codes()
    for code in codes:
        rows = read_tsv(LOCALES / f"{code}.tsv")
        ident = code.replace("-", "_")
        out.append(f"inline const char* const kText_{ident}[kKeyCount] = {{")
        for k in keys:
            out.append(f"    {c_string(rows[k]) if k in rows else 'nullptr'},  // {k}")
        out.append("};")
        out.append("")
    out.append(f"inline const char* const* const kColumns[{len(codes)}] = {{")
    for code in codes:
        out.append(f"    kText_{code.replace('-', '_')},")
    out.append("};")
    out.append("")
    out.append(f"inline const char* const kLangNames[{len(langs)}] = {{")
    for code, name in langs:
        out.append(f"    {c_string(name)},  // {code}")
    out.append("};")
    out += ["", "}  // namespace gen", "}  // namespace hmi", ""]
    return "\n".join(out)


def ranges_of_file() -> list[tuple[int, int]] | None:
    if not RANGES.exists():
        return None
    return [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\}", RANGES.read_text(encoding="utf-8"))]


def problems() -> list[str]:
    bad: list[str] = []
    keys = key_names()
    keyset = set(keys)
    if len(keys) != len(keyset):
        bad.append("core/locales.hpp: a key twice")
    try:
        langs = languages()
    except OSError as e:
        return [f"locales/names.tsv: {e}"]
    codes = [c for c, _ in langs]
    if codes[:8] != BASE or len(codes) != 37:
        bad.append("locales/names.tsv: the first eight languages are en es it de fr pt zh ja and there are thirty-seven")
    files = {p.stem for p in LOCALES.glob("*.tsv")} - {"names"}
    if files != set(extra_codes()):
        bad.append(f"locales: files {sorted(files ^ set(extra_codes()))} do not match names.tsv")
    for code in extra_codes():
        path = LOCALES / f"{code}.tsv"
        if not path.exists():
            continue
        try:
            rows = read_tsv(path)
        except ValueError as e:
            bad.append(str(e))
            continue
        variant = code in ("pt-br", "fr-ca")
        for k, v in rows.items():
            if k not in keyset:
                bad.append(f"{path.name}: key {k} does not exist")
            if not v.strip() or v != v.strip():
                bad.append(f"{path.name}: {k} is empty or has spaces at the ends")
            if "\t" in v or "\r" in v:
                bad.append(f"{path.name}: {k} has a control character")
        if not variant:
            missing = [k for k in keys if k not in rows]
            if missing:
                bad.append(f"{path.name}: {len(missing)} keys without text ({', '.join(missing[:4])}...)")
        for k, words in MUST_KEEP.items():
            if k in rows:
                for w in words:
                    if w not in rows[k]:
                        bad.append(f"{path.name}: {k} must keep '{w}'")
    ranges = ranges_of_file()
    if ranges is None:
        bad.append("core/font_ranges.hpp is missing (run tools/make_fonts.py)")
    else:
        lost = sorted(c for c in used_chars() if not any(a <= ord(c) <= b for a, b in ranges))
        if lost:
            bad.append("characters that are not in the font (run tools/make_fonts.py): " + "".join(lost[:40]))
    if not GEN.exists() or GEN.read_text(encoding="utf-8") != generate():
        bad.append("core/locales_gen.hpp is out of date (run tools/make_locales.py)")
    return bad


def main() -> int:
    if "--check" in sys.argv:
        bad = problems()
        for b in bad:
            print("FAIL", b)
        print("locales: " + ("PASS" if not bad else f"{len(bad)} problems"))
        return 1 if bad else 0
    GEN.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {GEN.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
